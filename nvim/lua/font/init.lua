--- Ghostty yazı tipi seçici: `:Font` komutu. Yazı tipini Ghostty çizer; bu modül seçimi
--- `~/.config/ghostty/font.ghostty` dosyasına `font-family = "..."` olarak yazar (config.ghostty bu dosyayı
--- `config-file = ?...` ile isteğe bağlı include eder) ve Ghostty'ye AppleScript ile `reload_config` gönderir.
--- Dosya yoksa Ghostty'nin varsayılanı (gömülü JetBrains Mono) geçerlidir. Testler `NVIM_FONT_FILE` ile
--- dosyayı başka yere yönlendirir.
local M = {}

M.default = "JetBrains Mono"

---@class FontEntry
---@field name string Ghostty'nin gördüğü aile adı (`ghostty +list-fonts`)
---@field cask string? Homebrew cask adı; nil = ücretli, elle kurulur

---@type FontEntry[]
M.fonts = {
  { name = "JetBrains Mono", cask = "font-jetbrains-mono" },
  { name = "Geist Mono", cask = "font-geist-mono" },
  { name = "Berkeley Mono" },
  { name = "Cascadia Code", cask = "font-cascadia-code" },
  { name = "Fira Code", cask = "font-fira-code" },
  { name = "Maple Mono", cask = "font-maple-mono" },
  { name = "IBM Plex Mono", cask = "font-ibm-plex-mono" },
  { name = "Monaspace Neon", cask = "font-monaspace" },
  { name = "Monaspace Argon", cask = "font-monaspace" },
  { name = "Monaspace Xenon", cask = "font-monaspace" },
  { name = "Monaspace Radon", cask = "font-monaspace" },
  { name = "Monaspace Krypton", cask = "font-monaspace" },
}

---@return string
function M.file()
  return vim.env.NVIM_FONT_FILE or vim.fn.expand("~/.config/ghostty/font.ghostty")
end

---@return string
local function ghostty_bin()
  return vim.fn.executable("ghostty") == 1 and "ghostty" or "/Applications/Ghostty.app/Contents/MacOS/ghostty"
end

--- Ghostty'nin bulabildiği yazı tipi aileleri (`+list-fonts` çıktısında girintisiz satırlar).
---@return table<string, boolean>
function M.installed()
  local set = {}
  local ok, res = pcall(function()
    return vim.system({ ghostty_bin(), "+list-fonts" }, { text = true }):wait(5000)
  end)
  if ok and res.code == 0 then
    for line in res.stdout:gmatch("[^\n]+") do
      if not line:match("^%s") then
        set[line] = true
      end
    end
  end
  return set
end

--- Seçili aile: dosyadaki son `font-family` satırı, yoksa varsayılan.
---@return string
function M.current()
  local name
  local ok, lines = pcall(vim.fn.readfile, M.file())
  for _, line in ipairs(ok and lines or {}) do
    name = line:match('^%s*font%-family%s*=%s*"(.-)"%s*$') or name
  end
  return (name and name ~= "") and name or M.default
end

--- `name`i (büyük/küçük harf ve boşluk duyarsız) listedeki kayda çevirir.
---@param name string
---@return FontEntry?
function M.find(name)
  local key = name:lower():gsub("%s+", "")
  for _, f in ipairs(M.fonts) do
    if f.name:lower():gsub("%s+", "") == key then
      return f
    end
  end
end

--- Açık Ghostty pencerelerine `reload_config` gönderir; olmazsa elle yeniden yükleme ipucu gösterir.
function M.reload()
  local script = 'if application "Ghostty" is running then tell application "Ghostty" to perform action '
    .. '"reload_config" on focused terminal of selected tab of front window'
  vim.system({ "osascript", "-e", script }, { text = true }, function(res)
    if res.code ~= 0 then
      vim.schedule(function()
        vim.notify("Font saved. Press Cmd+Shift+, to reload Ghostty", vim.log.levels.INFO)
      end)
    end
  end)
end

--- Yazı tipini kaydeder ve Ghostty'yi yeniden yükler. Kurulu olmayan yazı tipi reddedilir.
---@param name string
---@param installed table<string, boolean>?
---@return boolean
function M.set(name, installed)
  local f = M.find(name)
  if not f then
    vim.notify(("Unknown font: %s"):format(name), vim.log.levels.ERROR)
    return false
  end
  installed = installed or M.installed()
  if not installed[f.name] then
    local hint = f.cask and ("brew install --cask " .. f.cask)
      or "it is a commercial font; buy and install it from https://usgraphics.com/products/berkeley-mono"
    vim.notify(("%s is not installed (%s)"):format(f.name, hint), vim.log.levels.WARN)
    return false
  end
  local path = M.file()
  vim.fn.mkdir(vim.fs.dirname(path), "p")
  vim.fn.writefile({ "# Generated by :Font in Neovim", ('font-family = "%s"'):format(f.name) }, path)
  vim.notify(("Font: %s"):format(f.name))
  M.reload()
  return true
end

--- Seçici: mevcut yazı tipini ve kurulu olmayanları işaretler.
function M.pick()
  local installed, cur = M.installed(), M.current()
  vim.ui.select(M.fonts, {
    prompt = "Font",
    format_item = function(f)
      local tag = f.name == cur and "  (current)" or not installed[f.name] and "  (not installed)" or ""
      return f.name .. tag
    end,
  }, function(f)
    if f then
      M.set(f.name, installed)
    end
  end)
end

function M.setup()
  vim.api.nvim_create_user_command("Font", function(opts)
    if opts.args == "" then
      M.pick()
    else
      M.set(opts.args)
    end
  end, {
    nargs = "?",
    desc = "Switch Ghostty font",
    complete = function(lead)
      return vim.tbl_filter(function(n)
        return n:lower():find(lead:lower(), 1, true) == 1
      end, vim.tbl_map(function(f)
        return f.name
      end, M.fonts))
    end,
  })
end

return M
